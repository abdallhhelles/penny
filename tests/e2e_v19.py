#!/usr/bin/env python3
"""E2E for 1.9: interactive tour, translated/global report, update UI states, encryption status row."""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import e2e_harness as E
from playwright.sync_api import sync_playwright
check = E.check

def main():
    with sync_playwright() as pw:
        E.reset(); p, br, pg = E.session(pw)
        errs = []; pg.on('pageerror', lambda e: errs.append(str(e)))
        pg.wait_for_selector('#wn', timeout=10000); pg.fill('#wn', 'Lee'); pg.click('#wd')
        # ---- tour ----
        pg.wait_for_selector('.tour-root.on #tr_next', timeout=10000)
        check('T1 tour starts after setup with a personal welcome', 'Lee' in pg.inner_text('.tour-pop'))
        pg.click('#tr_next'); pg.wait_for_timeout(600)
        spot = pg.evaluate("(()=>{const s=document.querySelector('.tour-spot').getBoundingClientRect(),n=document.querySelector('#side .nav[data-nav=dashboard]').getBoundingClientRect();return Math.abs(s.left-(n.left-6))<2&&Math.abs(s.top-(n.top-6))<2})()")
        check('T2 spotlight sits on the real control', spot)
        pg.keyboard.press('ArrowRight'); pg.wait_for_timeout(500)
        check('T3 arrow key moves on, step shows the shortcut', 'N' in pg.inner_text('.tour-kbd'))
        pg.keyboard.press('ArrowLeft'); pg.wait_for_timeout(400)
        check('T4 back works', pg.evaluate("_tour.i") == 1)
        pg.keyboard.press('Escape'); pg.wait_for_timeout(500)
        check('T5 Esc closes and remembers it', pg.evaluate("!document.querySelector('.tour-root')&&S.settings.tourDone===true"))
        pg.evaluate("startTour(TOUR.length-1)"); pg.wait_for_timeout(500)
        check('T6 last step offers quick actions', pg.evaluate("document.querySelectorAll('.tour-quick [data-q]').length") == 3)
        pg.click('[data-q=add]'); pg.wait_for_timeout(900)
        check('T7 quick action opens the add sheet', pg.evaluate("!!document.querySelector('#modal.on')"))
        pg.evaluate("closeModal()")
        check('T8 tour is in the command palette', pg.evaluate("(openCmd(),document.querySelector('#cmd').innerText.includes('Take the tour'))"))
        pg.evaluate("closeCmd()")
        # ---- report, global + translated ----
        pg.evaluate("go('report')"); pg.wait_for_timeout(600)
        t = pg.evaluate("document.getElementById('view').innerText")
        check('R1 report has the glossary and PDF button', 'words used in this report' in t.lower() and pg.evaluate("!!document.getElementById('rp_pdf')"))
        check('R2 international sources are cited', 'Global Findex' in t and 'OECD' in t)
        pg.evaluate("S.settings.currency='EUR';S.settings.locale='de-DE';setupFmt();go('report')"); pg.wait_for_timeout(500)
        t = pg.evaluate("document.getElementById('view').innerText")
        check('R3 dollar-only threshold hidden for other currencies, DTI rule marked as country-dependent', 'Vanguard $2,000' not in t and 'depends on your country' in t)
        pg.evaluate("setAppLanguage('es')"); pg.wait_for_timeout(1500); pg.evaluate("go('report')"); pg.wait_for_timeout(600)
        t = pg.evaluate("document.getElementById('view').innerText")
        check('R4 report is translated (Spanish)', 'Informe de salud financiera' in t and 'prioridades' in t.lower() and 'priorities' not in t.lower(), t[:160])
        pg.evaluate("setAppLanguage('ar')"); pg.wait_for_timeout(1500); pg.evaluate("go('report')"); pg.wait_for_timeout(600)
        check('R5 report is translated (Arabic, right-to-left)', 'تقرير الصحة المالية' in pg.evaluate("document.getElementById('view').innerText") and pg.evaluate("document.documentElement.dir") == 'rtl')
        pg.evaluate("setAppLanguage('en')"); pg.wait_for_timeout(1500)
        pdf = E.mev("(async()=>{const w=__PENNY_ELECTRON.BrowserWindow.getAllWindows()[0];return (await w.webContents.printToPDF({printBackground:true})).length})()")
        check('R6 the window renders to PDF', isinstance(pdf, int) and pdf > 10000, str(pdf))
        # ---- updates ----
        st = pg.evaluate("native.updGet()")
        check('U1 update source is the GitHub repo', st.get('source') == 'github' and st.get('repo') == 'abdallhhelles/penny', str(st)[:200])
        pg.evaluate("onUpdate({...UPD,status:'downloading',available:'9.9.9',progress:.5})"); pg.wait_for_timeout(300)
        check('U2 top bar shows download progress', '50%' in pg.inner_text('#updbtn'))
        pg.evaluate("onUpdate({...UPD,status:'ready',available:'9.9.9',progress:1,notes:'- one\\n- two'})"); pg.wait_for_timeout(300)
        pg.click('#updbtn'); pg.wait_for_timeout(500)
        check('U3 update sheet: ready state with notes and restart button', pg.evaluate("!!document.getElementById('us_go')") and pg.evaluate("document.querySelectorAll('.upd-notes li').length") == 2)
        pg.evaluate("onUpdate({...UPD,status:'offline'})"); pg.wait_for_timeout(300)
        check('U4 sheet updates live (offline state)', 'offline' in pg.inner_text('.upd-sheet').lower())
        pg.evaluate("closeModal()")
        pg.evaluate("SET_CAT='about';go('settings')"); pg.wait_for_timeout(500)
        check('U5 Settings shows the update card with source', 'abdallhhelles/penny' in pg.inner_text('.upd-card'))
        pg.evaluate("SET_CAT='security';go('settings')"); pg.wait_for_timeout(500)
        check('S1 Security shows the encryption row', 'Encryption' in pg.evaluate("document.getElementById('view').innerText"))
        # ---- smoothness ----
        pg.evaluate("SET_CAT='look';go('settings')"); pg.wait_for_timeout(500)
        pg.evaluate("""(()=>{const v=document.getElementById('view');v.scrollTop=150;window.__keep=document.querySelector('#view .setsec');
          const sel=[...document.querySelectorAll('#view select')].find(e=>e.offsetParent);window.__sel=sel;sel.focus();window.__st=v.scrollTop;refresh();})()""")
        pg.wait_for_timeout(300)
        check('M1 a refresh updates the page in place (same elements, no rebuild)', pg.evaluate("window.__keep&&window.__keep.isConnected"))
        check('M2 focus and scroll stay where they were', pg.evaluate("document.activeElement===window.__sel&&document.getElementById('view').scrollTop===window.__st"))
        pg.locator('#view .switch').filter(has=pg.locator('input')).locator('visible=true').first.click(); pg.wait_for_timeout(500)
        check('M2b clicking a switch flips it without rebuilding the page', pg.evaluate("window.__keep.isConnected"))
        pg.evaluate("go('dashboard')"); pg.wait_for_timeout(500)
        pill = pg.evaluate("(()=>{const p=document.querySelector('.nav-pill').getBoundingClientRect(),n=document.querySelector('.nav.on').getBoundingClientRect();return Math.abs(p.top-n.top)<2&&Math.abs(p.height-n.height)<2})()")
        check('M3 sidebar pill sits on the active page', pill)
        pg.evaluate("document.getElementById('view').scrollTop=400"); pg.evaluate("go('budgets')"); pg.wait_for_timeout(300); pg.evaluate("go('dashboard')"); pg.wait_for_timeout(300)
        check('M4 each tab remembers its scroll position', abs(pg.evaluate("document.getElementById('view').scrollTop")-400) < 5)
        pg.evaluate("openTx()"); pg.wait_for_timeout(500); pg.evaluate("closeModal()")
        check('M5 closing a sheet plays an exit animation', pg.evaluate("!!document.querySelector('.modal-ghost')"))
        pg.wait_for_timeout(400)
        check('M6 the exit layer cleans itself up', pg.evaluate("!document.querySelector('.modal-ghost')"))
        # ---- brand + two themes ----
        pg.evaluate("SET_CAT='look';go('settings')"); pg.wait_for_timeout(400)
        check('B1 exactly two themes: Light and Dark', pg.evaluate("[...document.querySelectorAll('[data-th]')].map(b=>b.dataset.th).join()") == 'light,dark')
        pg.click('[data-th=light]'); pg.wait_for_timeout(500)
        check('B2 picking Light switches the app and saves it', pg.evaluate("document.documentElement.dataset.theme==='light'&&S.settings.theme==='light'"))
        pg.click('[data-th=dark]'); pg.wait_for_timeout(500)
        check('B3 brand tokens apply (Night background in dark)', pg.evaluate("getComputedStyle(document.documentElement).getPropertyValue('--bg1').trim().toUpperCase()") == '#10201D')
        pg.evaluate("S.settings.theme='auto';S.settings.style='glass';S.settings.accent='#FF375F';migrate(S);applySettings()"); pg.wait_for_timeout(300)
        check('B4 old auto / glass / accent settings settle on the brand look', pg.evaluate("['light','dark'].includes(S.settings.theme)&&document.documentElement.dataset.style==='clean'&&!document.documentElement.style.getPropertyValue('--accent')"))
        check('B5 sidebar shows the coin mark and the lowercase wordmark', pg.evaluate("document.querySelector('.brand .wordmark').textContent==='penny'&&document.querySelectorAll('.brand svg.pmark path').length===2"))
        check('B6 Sora is bundled and loads offline', pg.evaluate("document.fonts.check('600 20px Sora')"))
        # ---- profile pictures ----
        from PIL import Image, ImageDraw
        tmp = os.path.join(E.XDG, 'pics'); os.makedirs(tmp, exist_ok=True)
        im = Image.new('RGBA', (300, 500), (0, 0, 0, 0)); ImageDraw.Draw(im).ellipse((60, 160, 240, 340), fill=(201, 99, 47, 255)); im.save(tmp + '/clear.png')
        open(tmp + '/bad.png', 'wb').write(b'not an image')
        pg.evaluate("S.settings.avatar='🦊';S.settings.photo='';normalize(S);SET_CAT='you';go('settings')"); pg.wait_for_timeout(500)
        check('P1 avatars picked in older versions map to the new set', pg.evaluate("S.settings.avatar") == 'fox' and pg.evaluate("document.querySelector('[data-av=fox]').getAttribute('aria-checked')") == 'true')
        check('P2 sixteen brand avatars, each on a copper / evergreen / sand disc', pg.evaluate("[...document.querySelectorAll('#avs [data-av]')].filter(b=>/av-(cu|ev|sa)/.test(b.className)&&b.querySelector('svg.av-g')).length") == 16)
        pg.click('[data-av=owl]'); pg.wait_for_timeout(400)
        check('P3 picking one updates the profile and the sidebar', pg.evaluate("S.settings.avatar==='owl'&&!!document.querySelector('#sf .avatar svg.av-g')"))
        light = pg.evaluate("getComputedStyle(document.querySelector('#sf .avatar')).backgroundColor")
        pg.evaluate("S.settings.theme=S.settings.theme==='dark'?'light':'dark';applySettings()"); pg.wait_for_timeout(500)
        check('P4 avatar colours follow the theme', pg.evaluate("getComputedStyle(document.querySelector('#sf .avatar')).backgroundColor") != light)
        pg.set_input_files('#ph_file', tmp + '/clear.png'); pg.wait_for_timeout(900)
        px = pg.evaluate("""new Promise(r=>{const i=new Image();i.onload=()=>{const c=document.createElement('canvas');c.width=c.height=256;const g=c.getContext('2d');g.drawImage(i,0,0);r([c.width,i.width,...g.getImageData(4,4,1,1).data])};i.src=S.settings.photo})""")
        check('P5 a photo is cropped to a 256 px square; transparent areas are not black', px[1] == 256 and sum(px[2:5]) > 600, str(px))
        check('P6 the photo shows in the sidebar', pg.evaluate("!!document.querySelector('#sf .avatar.photo')"))
        pg.click('#ph_rm'); pg.wait_for_timeout(400); pg.set_input_files('#ph_file', tmp + '/clear.png'); pg.wait_for_timeout(900)
        check('P7 the same file can be picked again after removing it', bool(pg.evaluate("S.settings.photo")))
        pg.click('#ph_rm'); pg.wait_for_timeout(2600); pg.set_input_files('#ph_file', tmp + '/bad.png'); pg.wait_for_timeout(900)
        check('P8 a broken file is refused with a clear message', pg.evaluate("S.settings.photo") == '' and 'Could not read' in pg.evaluate("[...document.querySelectorAll('.toast')].map(t=>t.innerText).join('|')"))
        check('Z no page errors', not errs, str(errs[:3]))
        E.kill(p)
    ok = all(r for _, r in E.RESULTS)
    print(f"{sum(1 for _, r in E.RESULTS if r)}/{len(E.RESULTS)} checks passed")
    sys.exit(0 if ok else 1)

if __name__ == '__main__':
    main()
